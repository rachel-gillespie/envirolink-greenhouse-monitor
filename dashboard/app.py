from flask import Flask, render_template, jsonify, redirect, request
from flask_socketio import SocketIO
import sys
import os
# Add the backend directory to Python's path so we can import from it
# __file__ is the path to this file (app.py in dashboard/)
# We go up one level (..) then into backend/ to find db.py, weather.py etc.
sys.path.append(os.path.join(os.path.dirname(__file__), '..', 'backend'))
from db import connect_db, get_historical_data
import pytz
import paho.mqtt.client as mqtt
from dotenv import load_dotenv
import json
from datetime import datetime, timezone
import time
from weather import get_current_weather, get_forecast
import threading

load_dotenv()  # reads key-value pairs from a .env file and sets them as environment variables

ireland = pytz.timezone('Europe/Dublin')  # pytz allows accurate and cross-platform timezone calculations
app = Flask(__name__)
app.config['TEMPLATES_AUTO_RELOAD'] = True  # picks up template changes without restarting the server
app.config['SECRET_KEY'] = os.environ['SECRET_KEY']  # required by Flask-SocketIO for session security
socketio = SocketIO(app)

# --- Database Collections ---
db = connect_db()
readings_collection = db.readings    # incoming SenseHAT sensor readings
weather_collection = db.weather      # current outdoor weather from OpenWeatherMap
forecast_collection = db.forecast    # short-term forecast from OpenWeatherMap
alerts_collection = db.alerts        # alerts generated by the rules engine
config_collection = db.config        # user-defined thresholds from the settings page


# --- Weather Polling Thread ---
def fetch_weather_loop():
    """
    Background thread that fetches and stores current weather and forecast data
    from OpenWeatherMap every 3 hours. Runs independently of MQTT and HTTP traffic.
    """
    while True:
        weather = get_current_weather()
        if weather is None:
            time.sleep(60)  # API call failed — retry after 1 minute
            continue
        forecast = get_forecast()
        weather["timestamp"] = datetime.now(timezone.utc)
        forecast_doc = {
            "timestamp": datetime.now(timezone.utc),
            "forecast": forecast
        }
        forecast_collection.insert_one(forecast_doc)
        weather_collection.insert_one(weather)
        print(f"💾 Saved weather and forecast data")
        time.sleep(10800)  # poll every 3 hours (10800 seconds)

# daemon=True ensures this thread shuts down automatically when the main process exits
weather_thread = threading.Thread(target=fetch_weather_loop, daemon=True)
weather_thread.start()

# --- Rules Engine ---
def rules_engine(payload, latest_weather, latest_forecast):
    """
    Evaluate incoming sensor data against user-configured thresholds and outdoor conditions.
    Returns a list of alert dictionaries to be stored and displayed on the dashboard.
    """
    config = config_collection.find_one({})
    if config is None:
        print("⚠️ No config found in database. Run setup_config.py first.")
        return []

    alerts = []

    # Rule 1: Frost Prevention — triggered if outdoor OR indoor temp drops below minimum
    if latest_weather["temperature"] <= config["temp_min"] or payload["temperature"] < config["temp_min"]:
        alerts.append({"type": "danger", "msg": "🚨 Frost risk detected — activate heating!"})
        print(f"🚨 CRITICAL: Frost Risk Detected! Outdoor temperature is at freezing or indoor temperature has dropped below 10°C.")

    # Rule 2: Heat Stress — triggered if indoor temp exceeds maximum threshold
    if payload["temperature"] > config["temp_max"]:
        alerts.append({"type": "danger", "msg": "Heat Stress Risk - Activate cooling fans and open vents to lower the temperature!"})
        print(f"⚠️ WARNING: Heat Stress Risk! Greenhouse temperature has exceeded 30°C.")

    # Rule 3: High Humidity — risk of mould and plant disease above maximum threshold
    if payload["humidity"] > config["humidity_max"]:
        alerts.append({"type": "danger", "msg": "High Humidity Level - Initiate air circulation/de humidification!"})
        print(f"🌧️ NOTICE: High Humidity Level! Internal humidity is above 80%, increasing mold and disease risk.")

    # Rule 4: Low Humidity — risk of plant dehydration below minimum threshold
    if payload["humidity"] < config["humidity_min"]:
        alerts.append({"type": "danger", "msg": "Low Humidity Level - Activate misting system!"})
        print(f"🍂 WARNING: Low Humidity Level! Internal humidity has dropped below 40%. Plants are at risk of drying out.")

    # Rule 5: Smart Ventilation — outdoor air is cooler than indoor and indoor exceeds ventilation threshold
    if latest_weather["temperature"] < payload["temperature"] and payload["temperature"] > config["ventilation_temp"]:
        alerts.append({"type": "system optimisation", "msg": "Outdoor/Indoor temperature balance is optimal for natural ventilation - Open vents!"})
        print(f"🔄 SYSTEM OPTIMIZATION: Outdoor/Indoor temperature balance is optimal for natural ventilation.")

    # Rule 6: Irrigation Efficiency — skip watering if rain is in the upcoming forecast
    if any("rain" in slot["description"] for slot in latest_forecast["forecast"]):
        alerts.append({"type": "system optimisation", "msg": "Heavy rain detected outdoors - Conserve water by pausing watering!"})
        print(f"🔄 SYSTEM OPTIMIZATION: Heavy rain detected outdoors.")

    return alerts


# --- MQTT Callbacks ---
def on_connect(client, userdata, flags, reason_code, properties):
    """Called automatically by paho-mqtt when the broker connection is established or fails."""
    if reason_code == 0:
        print("✅ Connected to HiveMQ")
        client.subscribe("envirolink/sensors")  # subscribe to the topic published by the SenseHAT sensor script
        print("📡 Subscribed to envirolink/sensors")
    else:
        print(f"❌ Connection failed: {reason_code}")

def on_message(client, userdata, message):
    """
    Called automatically by paho-mqtt whenever a message arrives on a subscribed topic.
    Decodes the JSON payload, saves the reading to MongoDB, emits it to the dashboard
    via Socket.IO, and runs the rules engine to generate any new alerts.
    """
    try:
        payload = json.loads(message.payload.decode())
    except json.JSONDecodeError:
        print(f"⚠️ Invalid JSON received: {message.payload}")
        return

    payload["timestamp"] = datetime.now(timezone.utc)

    try:
        readings_collection.insert_one(payload)
    except Exception as e:
        print(f"⚠️ Failed to save reading to MongoDB: {e}")

    # Convert UTC timestamp to Irish local time before emitting to the dashboard
    # replace(tzinfo=...) stamps a naive datetime as UTC without converting it
    # astimezone(ireland) then converts that UTC time to Irish local time for display
    irish_time = payload['timestamp'].replace(tzinfo=timezone.utc).astimezone(ireland)
    socketio.emit('new_reading', {
        'temperature': payload['temperature'],
        'humidity': payload['humidity'],
        'pressure': payload['pressure'],
        'timestamp': irish_time.strftime('%H:%M:%S')
    })

    # Fetch the latest weather and forecast to cross-reference in the rules engine
    latest_weather = weather_collection.find_one({}, sort=[("timestamp", -1)])
    latest_forecast = forecast_collection.find_one({}, sort=[("timestamp", -1)])
    if latest_weather and latest_forecast:
        rules = rules_engine(payload, latest_weather, latest_forecast)
        for alert in rules:
            alert["timestamp"] = datetime.now(timezone.utc)
            alerts_collection.insert_one(alert)

    print(f"💾 Saved: {payload}")


# --- MQTT Client Setup ---
client = mqtt.Client(mqtt.CallbackAPIVersion.VERSION2)
client.username_pw_set(os.environ["MQTT_USERNAME"], os.environ["MQTT_PASSWORD"])  # os.environ returns a dictionary having the user's environmental variable as key and their values as value
client.tls_set()  # enable TLS encryption for the HiveMQ cloud broker connection
client.on_connect = on_connect
client.on_message = on_message

client.connect(os.environ["MQTT_BROKER"], int(os.environ["MQTT_PORT"]))
client.loop_start()  # starts a background thread to handle MQTT network traffic without blocking Flask

print("🔄 Backend running — waiting for messages. Ctrl+C to stop.")


# --- Flask Routes ---
@app.route('/')
def dashboard():
    """Render the main dashboard with the latest sensor reading, weather data, and recent alerts."""
    sensor_data = db.readings.find_one({}, sort=[("timestamp", -1)])  # most recent reading
    if sensor_data:
        sensor_data['timestamp'] = sensor_data['timestamp'].replace(tzinfo=pytz.utc).astimezone(ireland)
    else:
        # Fallback values shown before any MQTT messages have been received
        sensor_data = {
            "temperature": "N/A",
            "humidity": "N/A",
            "pressure": "N/A",
            "timestamp": "No data yet"
        }

    weather_data = db.weather.find_one({}, sort=[("timestamp", -1)])  # most recent weather fetch
    if not weather_data:
        weather_data = {
            "temperature": "N/A",
            "humidity": "N/A",
            "pressure": "N/A",
            "description": "No data yet"
        }

    alerts_data = db.alerts.find({}, sort=[("timestamp", -1)]).limit(5)  # 5 most recent alerts
    return render_template('index.html',
                           title="Dashboard",
                           sensor_data=sensor_data,
                           weather_data=weather_data,
                           alerts_data=alerts_data)

@app.route('/api/readings')
def return_readings():
    """Return the last 24 hours of sensor readings as JSON for the Chart.js graphs in dashboard.js."""
    history = get_historical_data()
    for reading in history:
        reading['_id'] = str(reading['_id'])  # convert ObjectId to string — ObjectId is not JSON serialisable
    return jsonify(history)

@app.route('/api/alerts')
def return_alerts():
    """Return the 5 most recent alerts as JSON, polled every 30 seconds by dashboard.js."""
    alerts = list(alerts_collection.find({}, sort=[("timestamp", -1)]).limit(5))
    for alert in alerts:
        alert['_id'] = str(alert['_id'])  # convert ObjectId to string — ObjectId is not JSON serialisable
    return jsonify(alerts)

@app.route('/settings', methods=['GET'])
def settings():
    """Render the settings page, pre-populated with the current config from MongoDB."""
    config = config_collection.find_one({})
    return render_template('settings.html', config=config)

@app.route('/settings', methods=['POST'])
def update_settings():
    """Handle settings form submission — update the single config document in MongoDB."""
    config_collection.update_one({}, {"$set": {  # $set updates only the specified fields, leaving others unchanged
        "temp_min": float(request.form['temp_min']),
        "temp_max": float(request.form['temp_max']),
        "humidity_min": float(request.form['humidity_min']),
        "humidity_max": float(request.form['humidity_max']),
        "ventilation_temp": float(request.form['ventilation_temp'])
    }})
    return redirect('/settings')

